def tile_prompt(region_desc, row, col):
    """逐块精修用的 prompt。region_desc 为视觉模型对该格的描述（可为空）。"""
    i = row * 3 + col
    name = REGION_NAMES[i]
    hint = REGION_HINTS[i]
    what = region_desc.strip() if region_desc and region_desc.strip() else hint
    return (
        "这是同一幅沙井村舆图的**%s局部放大图**（全图的第 %d 行第 %d 列）。\n"
        "该处画的是：%s。\n"
        "**保持原图的构图、屋宇位置、道路走向与色调完全不变**，"
        "只把细节画细：瓦垄要一根根写出来，院墙要有砖缝，篱笆要有枝条，"
        "树要有叶团与投影，地面要有土路、草痕与石板，屋顶与墙根要有影子。\n"
        "笔意仍是写意淡墨，不要改成工笔画，不要加新的房屋或道路。\n\n"
        % (name, row + 1, col + 1, what)
        + STYLE + "\n" + NEG
    )


def seam_prompt(vertical):
    a, b = ("左", "右") if vertical else ("上", "下")
    return (
        "这是一幅水墨乡村舆图上的一条接缝，接缝%s侧是%s半幅图、%s侧是%s半幅图。"
        "两半本是同一幅图，现在要对齐接缝。\n"
        "**只把接缝附近的内容接续起来**：房屋、院墙、道路、田埂、树影要在接缝处"
        "自然延续，色调、笔意、纸色完全一致。不要改动接缝两侧已经画好的内容，"
        "不要增删房屋。\n\n" % (a, a, b, b)
        + STYLE + "\n" + NEG
    )


